// THE ACCENTS' FILES: writes src/brand/accents.css from the palette in src/brand/accents.ts (the one place its colours
// are written), and the palette's swatches the SDK's docs show (../sdk/docs/accents.svg: the SDK names the accents but
// ships no colours). `npm run accents`; src/brand/accents.test.ts fails while a file on disk is not this output.
import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { APP_ACCENT_NAMES, APP_ACCENT_VARIABLES, DEFAULT_APP_ACCENT, appAccentColors, type AppAccentName, type AppAccentTone } from "../src/brand/accents"

export const ACCENTS_CSS = new URL("../src/brand/accents.css", import.meta.url)
export const ACCENTS_SVG = new URL("../../sdk/docs/accents.svg", import.meta.url)

/** The swatches: each name's fill and its text, light above, dark below. */
export function accentsSvg(): string {
  const width = APP_ACCENT_NAMES.length * 76 + 24
  const rows = APP_ACCENT_NAMES.map((name, i) => {
    const x = 12 + i * 76
    const { light, dark } = appAccentColors[name]
    const cell = (y: number, tone: AppAccentTone) =>
      `<rect x="${x + 12}" y="${y}" width="40" height="40" rx="10" fill="${tone.accent}"/><text x="${x + 32}" y="${y + 54}" text-anchor="middle" fill="${tone.text}" font-weight="600">${name}</text>`
    return `<g>${cell(12, light)}${cell(83, dark)}</g>`
  })
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="150" viewBox="0 0 ${width} 150" font-family="Inter, -apple-system, Segoe UI, Roboto, sans-serif" font-size="12">`,
    `<title>The apps' accents: ${APP_ACCENT_NAMES.join(", ")}, in light (above) and dark (below)</title>`,
    `<rect width="${width}" height="75" fill="#FFFFFF"/><rect y="75" width="${width}" height="75" fill="#0A0A0A"/>`,
    ...rows,
    "</svg>",
    "",
  ].join("\n")
}

const declarations = (tone: AppAccentTone, indent = "  ") =>
  (Object.keys(APP_ACCENT_VARIABLES) as (keyof AppAccentTone)[]).map((key) => `${indent}${APP_ACCENT_VARIABLES[key]}: ${tone[key]};`).join("\n")

const scope = (name: AppAccentName) =>
  `[data-app-accent="${name}"] {\n${declarations(appAccentColors[name].light)}\n}\n[data-app-accent="${name}"]:is(.dark, .dark *) {\n${declarations(appAccentColors[name].dark)}\n}`

/** The stylesheet, as accents.css holds it. */
export function accentsCss(): string {
  const base = appAccentColors[DEFAULT_APP_ACCENT]
  return `/*
 * THE APPS' ACCENTS. Generated by scripts/accents.ts from src/brand/accents.ts (\`npm run accents\`): do not edit.
 *
 * Every app has its own tint, one of the palette's names: \`data-app-accent="<name>"\` on the app's area (the shell's
 * <AppShell accent>, <AppAccent>) sets --app-accent, --app-accent-foreground and --app-accent-text, and points
 * the theme's roles of the app's own controls at them: the primary button, a switch, a progress bar, a checked box
 * and every selected state (--primary: theme.css «THE SELECTED STATE»), links and the focus ring (--link, --ring).
 * shadcn's components are not touched: they read those roles.
 * Outside an app's area (Clegra's rail, the account menu, the Faccina, the assistant) the roles stay Clegra's blue;
 * the status colours (--destructive, --success, --warning) are never the accent's.
 */
@theme inline {
  --color-app-accent: var(--app-accent);
  --color-app-accent-foreground: var(--app-accent-foreground);
  --color-app-accent-text: var(--app-accent-text);
}

/* Clegra's own accent, ${DEFAULT_APP_ACCENT}: outside every app's area, and the default. */
:root {
${declarations(base.light)}
}
.dark {
${declarations(base.dark)}
}

/* An app's area: its own controls follow its accent. */
[data-app-accent] {
  --primary: var(--app-accent);
  --primary-foreground: var(--app-accent-foreground);
  --ring: var(--app-accent-text);
  --link: var(--app-accent-text);
  --sidebar-primary: var(--app-accent);
  --sidebar-primary-foreground: var(--app-accent-foreground);
  --sidebar-ring: var(--app-accent-text);
  --sidebar-active: var(--app-accent-text);
}
/* The accent as text is --app-accent-text (a light fill, yellow or orange, is not text on white). */
[data-app-accent] .text-primary {
  color: var(--app-accent-text);
}

${APP_ACCENT_NAMES.map(scope).join("\n")}
`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(ACCENTS_CSS, accentsCss())
  writeFileSync(ACCENTS_SVG, accentsSvg())
  console.log(`written ${fileURLToPath(ACCENTS_CSS)}, ${fileURLToPath(ACCENTS_SVG)}`)
}
